const coverOf = (f: AtlasFrame) => FRAME_COVER[f.slug] ?? f.year;

/** 帝→帧：同段内取「coverFrom ≤ 在位起年」的最后一帧（即其登基时的疆域图） */
export function frameForNode(node: EmperorNode, frames: AtlasFrame[]): number {
  const inGroup = frames
    .map((f, i) => ({ f, i }))
    .filter(({ f }) => f.group === node.group);
  if (!inGroup.length) return 0;
  let pick = inGroup[0];
  for (const it of inGroup) {
    if (coverOf(it.f) <= node.start) pick = it;
  }
  return pick.i;
}

/** 帧→帝：同段内在位起年 ≥ 帧 coverFrom 的第一位（该图时段的开端之帝），无则取覆盖断面年者 */
export function nodeForFrame(frame: AtlasFrame, nodes: EmperorNode[]): number {
  const cover = coverOf(frame);
  const first = nodes.findIndex((n) => n.group === frame.group && n.start >= cover);
  if (first >= 0) return first;
  const covering = nodes.findIndex(
    (n) => n.start <= frame.year && frame.year <= n.end
  );
  if (covering >= 0) return covering;
  let best = 0;
  nodes.forEach((n, i) => {
    if (n.start <= frame.year) best = i;
  });
  return best;
}

/** 在位年展示：前141—前87 */
export function reignLabel(node: EmperorNode): string {
  const fmt = (y: number) => (y < 0 ? `前${-y}` : `${y}`);
  if (node.period) return `${fmt(node.start)}—${fmt(node.end)}`;
  return `在位 ${fmt(node.start)}—${fmt(node.end)}`;
}
